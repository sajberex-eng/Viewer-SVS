let current = 'ru';

export function setLanguage(lang) {
  if (STRINGS[lang]) current = lang;
  document.documentElement.lang = current;
}

export function t(key, params = {}) {
  const template = STRINGS[current][key] ?? STRINGS.ru[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}

// data-i18n задаёт текст, data-i18n-tip задаёт всплывающую подсказку и aria-label.
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // Короткое название кнопки-значка: программе чтения с экрана и меню «ещё»
  // нужна не длинная подсказка, а само действие (В-5).
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    const label = t(el.dataset.i18nLabel);
    el.setAttribute('aria-label', label);
    el.dataset.label = label;
  });
  root.querySelectorAll('[data-i18n-tip]').forEach((el) => {
    const tip = t(el.dataset.i18nTip);
    el.title = tip;
    if (!el.textContent.trim() && !el.dataset.label) el.setAttribute('aria-label', tip);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}

export function formatNumber(value, digits = 0) {
  return value.toLocaleString(current, { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

// Время от сервера приходит в UTC с отметкой «Z» и показывается по часам
// пользователя: «19.09.2026, 19:42» (ИН-1).
export function formatDateTime(iso) {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso ?? '';
  return date.toLocaleString(current, { dateStyle: 'short', timeStyle: 'short' });
}
